/// 每一个已收录的错误码都必须翻译出非空信息（覆盖全部 Some 分支）。
#[test]
fn test_all_codes_have_non_empty_msg() {
    assert_eq!(ALL_CODES.len(), 1832);
    for &code in ALL_CODES {
        let msg = find_msg_by_code(code)
            .unwrap_or_else(|| panic!("错误码 {code} 应被收录，实际返回 None"));
        assert!(!msg.is_empty(), "错误码 {code} 的翻译信息不应为空字符串");
    }
}

/// 未收录的错误码统一走兜底分支返回 `None`。
#[test]
fn test_unknown_code_returns_none() {
    assert_eq!(find_msg_by_code(999_999), None);
    assert_eq!(find_msg_by_code(0x7FFF_FFFF), None);
    assert_eq!(find_msg_by_code(-2), None);
    assert_eq!(find_msg_by_code(i32::MIN), None);
    assert_eq!(find_msg_by_code(i32::MAX), None);
}

